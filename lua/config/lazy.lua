-- Lazy.nvim Plugin Manager Setup
-- Bootstrap and configure lazy.nvim

-- Install lazy.nvim if not already installed
local lazypath = vim.fn.stdpath 'data' .. '/lazy/lazy.nvim'
if not vim.uv.fs_stat(lazypath) then
  local lazyrepo = 'https://github.com/folke/lazy.nvim.git'
  local out = vim.fn.system { 'git', 'clone', '--filter=blob:none', '--branch=stable', lazyrepo, lazypath }
  if vim.v.shell_error ~= 0 then
    error('Error cloning lazy.nvim:\n' .. out)
  end
end

---@type vim.Option
local rtp = vim.opt.rtp
rtp:prepend(lazypath)

-- Configure and setup lazy.nvim
require('lazy').setup({
  -- Import all plugin specs from plugins/ directory
  { import = 'plugins.core' },
  { import = 'plugins.ui' },
  { import = 'plugins.tools' },
  { import = 'plugins.lang' },
}, {
  -- Lazy.nvim configuration options
  ui = {
    -- Use unicode icons if available, otherwise fallback to ASCII
    icons = vim.g.have_nerd_font and {} or {
      cmd = '⌘',
      config = '🛠',
      event = '📅',
      ft = '📂',
      init = '⚙',
      keys = '🗝',
      plugin = '🔌',
      runtime = '💻',
      require = '🌙',
      source = '📄',
      start = '🚀',
      task = '📌',
      lazy = '💤 ',
    },
  },
  -- No luarocks/hererocks bootstrap; nothing here needs it
  rocks = { enabled = false },
  -- Don't nag about config files changing on disk
  change_detection = { notify = false },
  performance = {
    rtp = {
      -- Disable unused built-in plugins for a faster startup
      disabled_plugins = {
        'gzip',
        'tarPlugin',
        'tohtml',
        'tutor',
        'zipPlugin',
      },
    },
  },
})
